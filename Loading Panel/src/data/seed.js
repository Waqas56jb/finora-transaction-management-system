let seq = 0;

function uid(prefix) {
  seq += 1;
  return `${prefix}_${seq.toString(36)}`;
}

function iso(daysAgo, hours, minutes = 0) {
  const date = new Date();
  date.setSeconds(0, 0);
  date.setDate(date.getDate() - daysAgo);
  date.setHours(hours, minutes, 0, 0);
  return date.toISOString();
}

function timeline(createdAt, outcome, note) {
  const start = new Date(createdAt).getTime();
  const at = (seconds) => new Date(start + seconds * 1000).toISOString();
  const events = [
    {
      id: uid('evt'),
      at: at(0),
      title: 'Demo request created',
      detail: 'A simulated transaction record was stored in the local demo dataset.',
      simulated: true,
    },
    {
      id: uid('evt'),
      at: at(20),
      title: 'Input validation completed',
      detail: 'Required demo fields passed local validation. No identity was verified.',
      simulated: true,
    },
    {
      id: uid('evt'),
      at: at(40),
      title: 'Mock processing started',
      detail: 'No external network, bank, or card scheme was contacted.',
      simulated: true,
    },
  ];

  if (outcome === 'failed') {
    events.push({
      id: uid('evt'),
      at: at(70),
      title: 'Mock processing failed',
      detail: note || 'The demo workflow stopped locally. No funds were moved.',
      simulated: true,
    });
  } else if (outcome === 'pending') {
    events.push({
      id: uid('evt'),
      at: at(70),
      title: 'Demo record left pending',
      detail: note || 'The local record is pending. No external processing is running and no funds were moved.',
      simulated: true,
    });
  } else {
    events.push({
      id: uid('evt'),
      at: at(70),
      title: 'Mock processing completed',
      detail: note || 'The demo workflow finished locally. No funds were moved.',
      simulated: true,
    });
    events.push({
      id: uid('evt'),
      at: at(90),
      title: 'Receipt preview generated',
      detail: 'A demo receipt preview was prepared. It is not a financial instrument.',
      simulated: true,
    });
  }

  if (outcome === 'cancelled') {
    events.push({
      id: uid('evt'),
      at: at(180),
      title: 'Demo record cancelled',
      detail: 'The local demo record was cancelled. This does not reverse a real payment.',
      simulated: true,
    });
  }

  return events;
}

function txn(input) {
  const events = timeline(input.createdAt, input.outcome, input.note);
  const updatedAt = input.outcome === 'cancelled' ? events[events.length - 1].at : input.createdAt;
  return {
    id: input.id,
    reference: input.reference,
    transactionType: input.transactionType,
    accountType: input.accountType,
    protocolFamily: input.protocolFamily,
    protocolIdentifier: input.protocolIdentifier,
    protocolName: input.protocolName,
    serverProfileId: input.serverProfileId,
    serverProfileName: input.serverProfileName,
    environmentLabel: input.environmentLabel,
    currency: input.currency,
    amount: input.amount,
    description: input.description,
    referenceNote: input.referenceNote || '',
    account: input.account,
    sender: input.sender,
    receiver: input.receiver,
    status: input.status,
    createdAt: input.createdAt,
    updatedAt,
    receiptPreviewAt: input.outcome === 'completed' || input.outcome === 'cancelled' ? input.createdAt : null,
    approvalDemo: null,
    timeline: events,
    demoMode: true,
  };
}

